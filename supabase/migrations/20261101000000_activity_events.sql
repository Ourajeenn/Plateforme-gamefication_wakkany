-- ═════════════════════════════════════════════════
-- activity_events — Flux d'activité en direct (« Flux Live »)
-- ═════════════════════════════════════════════════
-- Une ligne par exploit publié (quête validée, compétence débloquée).
-- Lecture : tout utilisateur connecté. Écriture : uniquement sa propre ligne.
-- Aucune modification ni suppression côté client.

CREATE TABLE IF NOT EXISTS activity_events (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     UUID NOT NULL REFERENCES auth.users ON DELETE CASCADE,
  pseudo      TEXT NOT NULL CHECK (char_length(pseudo) BETWEEN 1 AND 40),
  message     TEXT NOT NULL CHECK (char_length(message) BETWEEN 1 AND 140),
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_activity_events_created ON activity_events (created_at DESC);

ALTER TABLE activity_events ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Connectés lisent le flux" ON activity_events;
CREATE POLICY "Connectés lisent le flux" ON activity_events
  FOR SELECT TO authenticated USING (true);

DROP POLICY IF EXISTS "Chacun publie son activité" ON activity_events;
CREATE POLICY "Chacun publie son activité" ON activity_events
  FOR INSERT TO authenticated WITH CHECK (user_id = auth.uid());

-- Diffusion en temps réel des nouvelles lignes
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables
    WHERE pubname = 'supabase_realtime' AND tablename = 'activity_events'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE activity_events;
  END IF;
END $$;
