-- ── 2. Débit de l'assistant en base ──────────────────────────
CREATE TABLE IF NOT EXISTS assistant_rate (
  user_id      UUID PRIMARY KEY REFERENCES auth.users ON DELETE CASCADE,
  window_start TIMESTAMPTZ NOT NULL DEFAULT now(),
  hits         INT NOT NULL DEFAULT 0
);

ALTER TABLE assistant_rate ENABLE ROW LEVEL SECURITY;
-- Aucune politique : seule la fonction SECURITY DEFINER ci-dessous y accède.

CREATE OR REPLACE FUNCTION assistant_hit(p_limit INT DEFAULT 10)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  allowed BOOLEAN;
BEGIN
  IF auth.uid() IS NULL THEN
    RETURN FALSE;
  END IF;

  INSERT INTO assistant_rate (user_id, window_start, hits)
  VALUES (auth.uid(), now(), 1)
  ON CONFLICT (user_id) DO UPDATE SET
    window_start = CASE
      WHEN assistant_rate.window_start < now() - interval '1 minute' THEN now()
      ELSE assistant_rate.window_start END,
    hits = CASE
      WHEN assistant_rate.window_start < now() - interval '1 minute' THEN 1
      ELSE assistant_rate.hits + 1 END
  RETURNING hits <= p_limit INTO allowed;

  RETURN allowed;
END;
$$;

REVOKE ALL ON FUNCTION assistant_hit(INT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION assistant_hit(INT) TO authenticated;

-- ── 3. Limite de gains d'XP par heure ────────────────────────
CREATE TABLE IF NOT EXISTS xp_grants (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    UUID NOT NULL REFERENCES auth.users ON DELETE CASCADE,
  amount     INT NOT NULL,
  granted_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_xp_grants_user_time ON xp_grants (user_id, granted_at DESC);

ALTER TABLE xp_grants ENABLE ROW LEVEL SECURITY;
-- Aucune politique : lecture et écriture uniquement via increment_xp.

CREATE OR REPLACE FUNCTION increment_xp(amount INTEGER)
RETURNS profiles AS $$
DECLARE
  updated_profile profiles;
  safe_amount INTEGER;
  grants_last_hour INTEGER;
BEGIN
  IF amount IS NULL OR amount <= 0 THEN
    RAISE EXCEPTION 'Le montant d''XP doit être positif';
  END IF;

  -- Garde-fou 1 : aucun gain ponctuel ne dépasse 500 XP
  safe_amount := LEAST(amount, 500);

  -- Garde-fou 2 : au plus 30 gains par heure et par utilisateur
  SELECT COUNT(*) INTO grants_last_hour
  FROM xp_grants
  WHERE user_id = auth.uid()
    AND granted_at > now() - interval '1 hour';

  IF grants_last_hour >= 30 THEN
    RAISE EXCEPTION 'Limite de gains d''XP atteinte, réessaie plus tard';
  END IF;

  INSERT INTO xp_grants (user_id, amount) VALUES (auth.uid(), safe_amount);

  PERFORM set_config('app.allow_profile_update', 'true', true);

  UPDATE profiles
  SET xp = xp + safe_amount,
      level = FLOOR((xp + safe_amount) / 100) + 1
  WHERE id = auth.uid()
  RETURNING * INTO updated_profile;

  PERFORM set_config('app.allow_profile_update', 'false', true);

  IF updated_profile IS NULL THEN
    RAISE EXCEPTION 'Profil introuvable pour cet utilisateur';
  END IF;

  RETURN updated_profile;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp;

