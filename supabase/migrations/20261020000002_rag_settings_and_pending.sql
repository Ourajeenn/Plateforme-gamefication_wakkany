CREATE TABLE IF NOT EXISTS assistant_pending (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  question TEXT NOT NULL,
  proposed_answer TEXT NOT NULL,
  source_ids BIGINT[] DEFAULT '{}',
  status TEXT DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
  created_at TIMESTAMPTZ DEFAULT now(),
  reviewed_by UUID REFERENCES auth.users ON DELETE SET NULL,
  reviewed_at TIMESTAMPTZ
);

ALTER TABLE assistant_pending ENABLE ROW LEVEL SECURITY;

-- Aucune lecture publique : seul l'admin voit les réponses en attente
CREATE POLICY "assistant_pending_admin_read"
  ON assistant_pending FOR SELECT
  USING (EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid() AND role = 'admin'));

CREATE POLICY "assistant_pending_admin_update"
  ON assistant_pending FOR UPDATE
  USING (EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid() AND role = 'admin'))
  WITH CHECK (EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid() AND role = 'admin'));
