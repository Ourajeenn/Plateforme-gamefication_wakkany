CREATE TABLE IF NOT EXISTS app_settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT now(),
  updated_by UUID REFERENCES auth.users ON DELETE SET NULL
);

INSERT INTO app_settings (key, value)
VALUES ('assistant_mode', 'supervised')
ON CONFLICT (key) DO NOTHING;

ALTER TABLE app_settings ENABLE ROW LEVEL SECURITY;

-- Lecture : tout le monde peut connaître le mode (il n'est pas secret)
CREATE POLICY "app_settings_read"
  ON app_settings FOR SELECT
  USING (true);

-- Écriture : uniquement les administrateurs
CREATE POLICY "app_settings_admin_write"
  ON app_settings FOR UPDATE
  USING (
    EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid() AND role = 'admin')
  )
  WITH CHECK (
    EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid() AND role = 'admin')
  );

-- Contrainte de valeur : seules trois valeurs sont autorisées
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'assistant_mode_valid'
  ) THEN
    ALTER TABLE app_settings
      ADD CONSTRAINT assistant_mode_valid
      CHECK (key <> 'assistant_mode' OR value IN ('off', 'auto', 'supervised'));
  END IF;
END $$;

