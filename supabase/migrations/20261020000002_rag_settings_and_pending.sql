-- Table minimaliste clé/valeur pour la configuration de l'appli.
-- Une seule ligne est utilisée pour l'instant : assistant_mode.
CREATE TABLE IF NOT EXISTS app_settings (
  key        TEXT PRIMARY KEY,
  value      TEXT NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_by UUID REFERENCES auth.users ON DELETE SET NULL
);

COMMENT ON TABLE app_settings IS
  'Configuration globale de l''application. '
  'Chaque ligne est une paire clé/valeur. '
  'Seuls les admins peuvent écrire ; tout le monde peut lire.';

-- Valeur initiale : mode supervisé (le plus sûr).
-- ON CONFLICT : si la ligne existe déjà (migration rejouée), on ne l'écrase pas.
INSERT INTO app_settings (key, value)
VALUES ('assistant_mode', 'supervised')
ON CONFLICT (key) DO NOTHING;

-- ============================================================
-- RLS
-- ============================================================
ALTER TABLE app_settings ENABLE ROW LEVEL SECURITY;

-- Lecture publique (la Edge Function en anon peut lire le mode)
CREATE POLICY "Public read app_settings" ON app_settings
  FOR SELECT USING (true);

-- Seuls les admins peuvent modifier
CREATE POLICY "Admins write app_settings" ON app_settings
  FOR ALL USING (
    EXISTS (
      SELECT 1 FROM profiles
      WHERE profiles.id = auth.uid()
        AND profiles.role = 'admin'
    )
  )
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM profiles
      WHERE profiles.id = auth.uid()
        AND profiles.role = 'admin'
    )
  );

-- ============================================================
-- Migration RAG Step 8 : table assistant_pending
-- Questions posées en mode 'supervised' en attente de réponse
-- manuelle de l'admin.
-- ============================================================
CREATE TABLE IF NOT EXISTS assistant_pending (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     UUID REFERENCES auth.users ON DELETE SET NULL,
  prompt      TEXT NOT NULL,
  created_at  TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  handled     BOOLEAN DEFAULT FALSE,
  handled_at  TIMESTAMP WITH TIME ZONE,
  handled_by  UUID REFERENCES auth.users ON DELETE SET NULL,
  admin_reply TEXT
);

COMMENT ON TABLE assistant_pending IS
  'File d''attente des questions posées à l''assistant en mode supervised. '
  'L''admin répond manuellement ; le joueur voit la réponse dès qu''handled = TRUE.';

ALTER TABLE assistant_pending ENABLE ROW LEVEL SECURITY;

-- Un joueur peut lire ses propres questions en attente
CREATE POLICY "Users read own pending" ON assistant_pending
  FOR SELECT USING (auth.uid() = user_id);

-- Un joueur peut insérer sa propre question
CREATE POLICY "Users insert own pending" ON assistant_pending
  FOR INSERT WITH CHECK (auth.uid() = user_id);

-- Les admins voient tout et peuvent répondre
CREATE POLICY "Admins manage pending" ON assistant_pending
  FOR ALL USING (
    EXISTS (
      SELECT 1 FROM profiles
      WHERE profiles.id = auth.uid()
        AND profiles.role = 'admin'
    )
  );

-- Index pour la file d'attente admin (questions non traitées en premier)
CREATE INDEX IF NOT EXISTS idx_assistant_pending_unhandled
  ON assistant_pending (created_at DESC)
  WHERE handled = FALSE;
